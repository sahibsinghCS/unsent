"""Play a fixed message list through the real app (no AI wording) and write the transcript the
landing page shows, so every number on it is one the engine actually computed.

    PYTHONPATH=. uv run python scripts/demo_transcript.py   # sets FR_LLM=0, FR_EMBED=fastembed
"""

from __future__ import annotations

import json
import os
import sys
from pathlib import Path

os.environ["FR_LLM"] = "0"
os.environ.setdefault("FR_EMBED", "fastembed")

from fastapi.testclient import TestClient  # noqa: E402

from backend.app.main import app  # noqa: E402

SCENARIO = "after-the-breakup"
SCRIPTS = {
    "en": [
        "hey, you've seemed off lately. you ok?",
        "lol you'll be fine",
        "sorry, that was a dumb thing to say. that sounds really hard",
        "it makes sense you feel that way. i'm here",
        "that sounds so lonely. you don't have to deal with this alone",
        "i'm not going anywhere. you can tell me anything",
        "are you thinking about killing yourself?",
        "i'm really glad you're talking to me. can we talk to the counselor tomorrow? i'll go with you",
    ],
    "es": [
        "oye, te he notado rara últimamente. ¿estás bien?",
        "jaja no es para tanto, vas a estar bien",
        "perdón, eso fue tonto. eso suena muy difícil",
        "tiene sentido que te sientas así. aquí estoy",
        "eso suena muy solitario. no tienes que pasar por esto sola",
        "no me voy a ir a ningún lado. me puedes contar lo que sea",
        "¿estás pensando en suicidarte?",
        "me alegra mucho que me estés hablando. ¿hablamos con la consejera mañana? yo te acompaño",
    ],
}
OUT = Path(__file__).resolve().parents[1] / "content" / "demo_transcript.json"


def run(client: TestClient, locale: str) -> dict:
    session = client.post("/api/sessions", json={"scenario_id": SCENARIO, "locale": locale}).json()
    sid = session["session_id"]
    turns = []
    for text in SCRIPTS[locale]:
        turn = client.post(f"/api/sessions/{sid}/messages", json={"text": text}).json()
        friend = turn.get("friend_node") or {}
        events = turn["user_node"].get("events") or {}
        guardian = turn["user_node"].get("guardian") or {}
        turns.append(
            {
                "you": text,
                "friend": friend.get("bubbles", []),
                "seen": bool(friend.get("seen_no_reply")),
                "line_id": friend.get("line_id"),
                "skills": sorted(k for k, v in events.items() if v >= 0.5),
                "guardian": guardian.get("action"),
                "guardian_ms": round(guardian.get("latency_ms", 0.0), 1),
                "trust_before": round(turn["state_before"]["trust"]),
                "trust_after": round(turn["state_after"]["trust"]),
                "level_after": turn["state_after"]["level"],
            }
        )
    return {"scenario": SCENARIO, "opening": session["nodes"][0]["bubbles"], "turns": turns}


def main() -> int:
    client = TestClient(app)
    run(client, "en")  # warm-up: model loading time is not the safety check's speed
    data = {locale: run(client, locale) for locale in SCRIPTS}
    data["note"] = "Generated by scripts/demo_transcript.py: a real run, FR_LLM=0 (reviewed lines)."
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    for locale in SCRIPTS:
        print(f"== {locale}: {data[locale]['opening']}")
        for t in data[locale]["turns"]:
            print(f"  you: {t['you']}")
            print(
                f"     {t['trust_before']}->{t['trust_after']} L{t['level_after']} {t['skills']} "
                f"guardian={t['guardian']} {t['guardian_ms']}ms seen={t['seen']}"
            )
            print(f"  friend: {t['friend']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
